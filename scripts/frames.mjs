// Generates src/ui/css/frames-wallet.css, which overrides frames.css: the same glyph shapes with square ('+') corners,
// drawn in white and greys. Run it again after changing a colour: node scripts/frames.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const CSS = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'ui', 'css');
// plum's inks, and what each becomes here
const INK = {
  '#cbbfe8': '#d6d6d6', // ink
  '#66588a': '#5c5c5c', // soft
  '#2c243c': '#2a2a2a', // faint
  '#a986ff': '#ffffff', // the accent
  '#110d17': '#110d17', // paper: plum's night, as it was
  '#ff8a4c': '#ff8a4c', // hot: warnings keep their colour
  '#ff6f61': '#ff6f61', // red: dangers keep theirs
  '#6ea8f5': '#6ea8f5', // blue
};

const r = (x, y, w, h) => `<rect x='${x}' y='${y}' width='${w}' height='${h}'/>`;
// a '+' whose crossing sits on the dash line at y (its arms reach 0.235 above and below it), as plum's frames-sq.mjs
const plus = (x0, y) => r(x0 + 0.065, y, 0.47, 0.08) + r(x0 + 0.255, +(y - 0.195).toFixed(3), 0.09, 0.47);
const url = (svg) => `url("data:image/svg+xml,${svg.replace(/</g, '%3C').replace(/>/g, '%3E').replace(/#/g, '%23')}")`;

/** A square border-image: corners '+', edges '-' and '|'. full: 1.538em lines top and bottom (boxes); half: 0.769em. */
function square(fill, full) {
  const top = full ? 1.538462 : 0.769231;
  const h = +(top * 2 + 1.538462).toFixed(3);
  const dashTop = full ? 0.759 : 0.345;
  const dashBot = +(top + 1.538462 + dashTop).toFixed(3);
  const barY = +(top + 0.299).toFixed(3);
  const shapes = [
    plus(0, dashTop), r(0.74, dashTop, 0.32, 0.08), plus(1.2, dashTop),
    r(0.255, barY, 0.09, 0.94), r(1.455, barY, 0.09, 0.94),
    plus(0, dashBot), r(0.74, dashBot, 0.32, 0.08), plus(1.2, dashBot),
  ].join('');
  return url(`<svg xmlns='http://www.w3.org/2000/svg' width='180' height='${+(h * 100).toFixed(3)}' viewBox='0 0 1.8 ${h}' fill='${fill}'>${shapes}</svg>`);
}

const src = readFileSync(join(CSS, 'frames.css'), 'utf8');
const out = [];
for (const [, name, value] of src.matchAll(/^\s*(--[a-z0-9-]+): (url\("data:image\/svg\+xml,[^"]*"\));$/gm)) {
  const fills = [...value.matchAll(/(?:fill|stroke)='%23([0-9a-f]{6})'/g)].map((m) => `#${m[1]}`);
  for (const f of fills) if (!(f in INK)) throw new Error(`${name}: no wallet ink for ${f}`);
  // the boxes and the small boxes (inputs, buttons, notes): square, in the new ink
  if (/^--frh?-(ink|soft|faint|green|hot|red|blue|paper)$/.test(name)) out.push(`  ${name}: ${square(INK[fills[0]], name.startsWith('--fr-'))};`);
  // everything else (rules, dots, pills): the same shapes, recoloured
  else out.push(`  ${name}: ${value.replace(/((?:fill|stroke)='%23)([0-9a-f]{6})'/g, (m, p, hex) => `${p}${INK[`#${hex}`].slice(1)}'`)};`);
}
const text = `/* The wallet's typed frames: generated by scripts/frames.mjs from frames.css (don't edit by hand). Square boxes, black
 * and white inks; loaded after frames.css, so these win. */\n:root {\n${out.join('\n')}\n}\n`;
writeFileSync(join(CSS, 'frames-wallet.css'), text);
console.log(`wrote ${out.length} frames into src/ui/css/frames-wallet.css`);
