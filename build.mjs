// Build plum from src/ for both browser families:
//   dist/firefox/    Firefox (its background is an event page; the manifest is src/manifest.json as it is)
//   dist/chromium/   Chrome, Brave, Edge and Opera (the same files; the manifest is made from src's, see below)
// Scripts are bundled by esbuild (readable, not minified, so anyone can check what runs); pages, styles, font and
// icons are copied as they are.
//   node build.mjs              once
//   node build.mjs --watch      rebuild both on change
//   node build.mjs --rpc <url>  with another mainnet RPC (see below); --own-rpc, with yours from rpc.local.txt
import { context, build } from 'esbuild';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(fileURLToPath(import.meta.url));
const SRC = join(ROOT, 'src');
const DIST = join(ROOT, 'dist');
const watch = process.argv.includes('--watch');

// the icon dApps show beside "Plum" in their wallet lists: the toolbar's typed plum (scripts/icons.mjs)
const icon = readFileSync(join(SRC, 'icons', '128.png'));
writeFileSync(join(SRC, 'content', 'icon.js'), `// Generated by build.mjs from icons/128.png: don't edit.\nexport const ICON = 'data:image/png;base64,${icon.toString('base64')}';\n`);

// mainnet's RPC: plum's own, https://plum.fun/rpc (src/background/rpc.js), a proxy that keeps the RPC key on plum's
// server, so a build holds nothing secret and can go to anyone. Settings can still point plum elsewhere. Two others:
//   --rpc <url>   mainnet goes to <url> instead: https://, or http:// on this computer (a local proxy, for tests)
//   --own-rpc     mainnet goes straight to the URL in rpc.local.txt (kept out of src/ and git), key and all: a copy for
//                 your own install only. Anyone holding it can dig the key out, so never publish it.
// A build without --own-rpc is checked for that key before it counts as built.
const RPC_FILE = join(ROOT, 'rpc.local.txt');
const flagValue = (flag) => { const i = process.argv.indexOf(flag); return i > 0 ? process.argv[i + 1] ?? '' : null; };
const ownRpc = process.argv.includes('--own-rpc');
let mainnetRpc = flagValue('--rpc') ?? '';
if (ownRpc) {
  if (!existsSync(RPC_FILE)) throw new Error('--own-rpc needs rpc.local.txt (one line: your RPC URL with its key)');
  mainnetRpc = readFileSync(RPC_FILE, 'utf8').trim();
}
if (mainnetRpc) {
  // an error here never quotes the URL: it may hold a key
  let u;
  try { u = new URL(mainnetRpc); } catch { throw new Error(`${ownRpc ? 'rpc.local.txt' : '--rpc'}: that isn't a URL`); }
  const local = ['localhost', '127.0.0.1', '[::1]'].includes(u.hostname);
  if (!(u.protocol === 'https:' || (u.protocol === 'http:' && local)) || u.username || u.password) {
    throw new Error(`${ownRpc ? 'rpc.local.txt' : '--rpc'}: the RPC must be https:// (http:// only on this computer), with any key in the path or query`);
  }
}

/** Stop if a build meant for anyone holds the key from rpc.local.txt: its query values and long path parts. */
function checkKeyless() {
  if (ownRpc || !existsSync(RPC_FILE)) return;
  let u;
  try { u = new URL(readFileSync(RPC_FILE, 'utf8').trim()); } catch { return; }
  const secrets = [...u.searchParams.values(), ...u.pathname.split('/')].filter((s) => s.length >= 16).map((s) => Buffer.from(s));
  for (const target of TARGETS) {
    const dir = join(DIST, target.name);
    for (const f of readdirSync(dir, { recursive: true })) {
      const path = join(dir, f);
      if (statSync(path).isFile() && secrets.some((s) => readFileSync(path).includes(s))) {
        rmSync(DIST, { recursive: true, force: true });
        console.error(`dist/${target.name}/${f} holds the RPC key from rpc.local.txt, so dist/ is deleted: a build for anyone must not`);
        process.exit(1);
      }
    }
  }
}

/** Chromium's manifest: src's, with a service worker for the background (Chromium has no event pages), the oldest
 * Chrome plum supports, and without Firefox's own settings. Everything else stays the same. */
function chromiumManifest(manifest) {
  const out = { ...manifest, background: { service_worker: 'background.js' }, minimum_chrome_version: '120' };
  delete out.browser_specific_settings;
  return out;
}

// Firefox takes src/manifest.json as it is; a target with a `manifest` function gets its own, made from it
const TARGETS = [
  { name: 'firefox', esbuild: 'firefox128', hint: 'load dist/firefox/manifest.json in about:debugging' },
  { name: 'chromium', esbuild: 'chrome120', manifest: chromiumManifest, hint: 'load dist/chromium/ unpacked in chrome://extensions' },
];

const statics = [
  ['ui/popup.html', 'popup.html'],
  ['ui/approve.html', 'approve.html'],
  ['ui/css', 'css'],
  ['ui/fonts', 'fonts'],
  ['icons', 'icons'],
];
function copyStatics(target) {
  const out = join(DIST, target.name);
  for (const [from, to] of statics) cpSync(join(SRC, from), join(out, to), { recursive: true });
  const manifest = join(SRC, 'manifest.json');
  if (!target.manifest) cpSync(manifest, join(out, 'manifest.json'));
  else writeFileSync(join(out, 'manifest.json'), `${JSON.stringify(target.manifest(JSON.parse(readFileSync(manifest, 'utf8'))), null, 2)}\n`);
}

const options = (target) => ({
  entryPoints: {
    background: join(SRC, 'background/entry.js'),
    inject: join(SRC, 'content/inject.js'),
    bridge: join(SRC, 'content/bridge.js'),
    popup: join(SRC, 'ui/popup.js'),
    approve: join(SRC, 'ui/approve.js'),
  },
  outdir: join(DIST, target.name),
  bundle: true,
  format: 'iife',
  target: [target.esbuild],
  minify: false,
  legalComments: 'eof',
  charset: 'utf8',
  // warnings and errors only: esbuild's own summary is a table of files per build, and each target prints one line
  logLevel: 'warning',
  define: mainnetRpc ? { __PLUM_MAINNET_RPC__: JSON.stringify(mainnetRpc) } : {},
});
console.log(`mainnet rpc: ${ownRpc ? `YOURS, straight to ${new URL(mainnetRpc).host} with the key from rpc.local.txt: this copy is for your own install only, never publish it` : mainnetRpc ? `${new URL(mainnetRpc).host} (--rpc)` : "plum's own (https://plum.fun/rpc)"}`);

// dist/ holds only the two folders, fresh each time
rmSync(DIST, { recursive: true, force: true });
for (const target of TARGETS) mkdirSync(join(DIST, target.name), { recursive: true });

if (watch) {
  for (const target of TARGETS) {
    const after = { name: 'statics', setup(b) {
      b.onEnd((result) => {
        copyStatics(target);
        if (!result.errors.length) console.log(`built dist/${target.name}/ at ${new Date().toLocaleTimeString()}`);
      });
    } };
    const ctx = await context({ ...options(target), plugins: [after] });
    await ctx.watch();
  }
  console.log('watching src/ for both builds (ctrl+c to stop)');
} else {
  for (const target of TARGETS) {
    copyStatics(target);
    // when a build fails, esbuild has already printed why
    await build(options(target)).catch(() => { console.error(`dist/${target.name}/ not built`); process.exit(1); });
    console.log(`built dist/${target.name}/ (${target.esbuild}): ${target.hint}`);
  }
  checkKeyless();
}
